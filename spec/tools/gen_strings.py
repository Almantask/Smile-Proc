#!/usr/bin/env python3
"""Generate iOS and Android string files from spec/strings/en.json.

    python3 spec/tools/gen_strings.py
    python3 spec/tools/gen_strings.py --check
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "spec" / "strings" / "en.json"
IOS_OUT = ROOT / "ios" / "App" / "Resources" / "Localizable.xcstrings"
ANDROID_OUT = ROOT / "android" / "app" / "src" / "main" / "res" / "values" / "strings.xml"
PLACEHOLDER = re.compile(r"\{([A-Za-z][A-Za-z0-9]*)\}")
INT_NAMES = {"count", "hour", "minute", "days"}
HEADER = "DO NOT EDIT. Generated by spec/tools/gen_strings.py from spec/strings/en.json."


def convert(text: str, platform: str) -> str:
    matches = list(PLACEHOLDER.finditer(text))
    if not matches:
        return text
    pieces = []
    last = 0
    for index, match in enumerate(matches, start=1):
        pieces.append(text[last : match.start()])
        is_int = match.group(1) in INT_NAMES
        if platform == "ios":
            if len(matches) == 1:
                pieces.append("%lld" if is_int else "%@")
            else:
                pieces.append(f"%{index}$lld" if is_int else f"%{index}$@")
        else:
            pieces.append(f"%{index}$d" if is_int else f"%{index}$s")
        last = match.end()
    pieces.append(text[last:])
    return "".join(pieces)


def xml_escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("'", "\\'")
        .replace('"', '\\"')
    )


def android_name(key: str) -> str:
    return key.replace(".", "_")


def render_ios(strings: dict[str, str]) -> str:
    payload = {
        "sourceLanguage": "en",
        "strings": {},
        "version": "1.0",
    }
    for key in sorted(strings):
        payload["strings"][key] = {
            "comment": HEADER,
            "extractionState": "manual",
            "localizations": {
                "en": {
                    "stringUnit": {
                        "state": "translated",
                        "value": convert(strings[key], "ios"),
                    }
                }
            },
        }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def render_android(strings: dict[str, str]) -> str:
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        f"<!-- {HEADER} -->",
        "<resources>",
    ]
    seen = {}
    for key in sorted(strings):
        name = android_name(key)
        if name in seen:
            raise SystemExit(f"string name collision: {key} and {seen[name]}")
        seen[name] = key
        lines.append(f'    <string name="{name}">{xml_escape(convert(strings[key], "android"))}</string>')
    lines.append("</resources>")
    lines.append("")
    return "\n".join(lines)


def load_strings() -> dict[str, str]:
    raw = json.loads(SOURCE.read_text())
    if not isinstance(raw, dict):
        raise SystemExit("en.json must be an object")
    for key, value in raw.items():
        if not isinstance(value, str):
            raise SystemExit(f"{key} is not a string")
    return raw


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    strings = load_strings()
    ios = render_ios(strings)
    android = render_android(strings)
    if args.check:
        ok = True
        for path, text in ((IOS_OUT, ios), (ANDROID_OUT, android)):
            if not path.exists() or path.read_text() != text:
                print(f"string drift: {path.relative_to(ROOT)}")
                ok = False
        if not ok:
            return 1
        print("strings match the generator")
        return 0
    IOS_OUT.parent.mkdir(parents=True, exist_ok=True)
    ANDROID_OUT.parent.mkdir(parents=True, exist_ok=True)
    IOS_OUT.write_text(ios)
    ANDROID_OUT.write_text(android)
    print(f"wrote {IOS_OUT.relative_to(ROOT)} and {ANDROID_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
